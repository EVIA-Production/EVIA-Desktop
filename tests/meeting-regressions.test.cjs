const assert = require('node:assert/strict')
const test = require('node:test')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8')

test('active capture identity outranks shared and local chat preferences', () => {
  const source = read('src/renderer/services/websocketService.ts')
  const resolver = source.slice(source.indexOf('export async function getOrCreateChatId'))
  assert.ok(resolver.indexOf('capture?.chatId') < resolver.indexOf("localStorage.getItem('current_chat_id')"))
  assert.match(resolver, /if \(forceCreate\) throw new Error\('End the active call/)
})

test('language changes preserve the live meeting before any reset path', () => {
  const source = read('src/renderer/overlay/overlay-entry.tsx')
  const toggle = source.slice(source.indexOf('const handleToggleLanguage'), source.indexOf('const OverlayApp'))
  const active = toggle.indexOf("['starting', 'recording', 'stopping', 'review']")
  assert.ok(active > 0)
  const branch = toggle.slice(active, toggle.indexOf('const activeHandle', active))
  assert.match(branch, /i18n.setLanguage\(newLang\)/)
  assert.match(branch, /return/)
  assert.doesNotMatch(branch, /clear-session|reconcileNoCapture|stopCapture/)
  const ask = read('src/renderer/overlay/AskView.tsx')
  const handler = ask.slice(ask.indexOf('const handleLanguageChanged'), ask.indexOf('const handleShortcutNextStep'))
  assert.doesNotMatch(handler, /current_chat_id|setResponseHistory\(\[\]\)|setResponse\(''\)/)
})

test('header and child windows share the local DevTools shortcut handler', () => {
  const source = read('src/main/overlay-windows.ts')
  const start = source.indexOf('function configureContentZoomShortcuts')
  const handler = source.slice(start, start + 1800)
  assert.match(handler, /devToolsChord/)
  assert.match(handler, /input.meta && input.alt/)
  assert.match(source, /configureContentZoomShortcuts\(headerWindow\)/)
  assert.match(source, /configureContentZoomShortcuts\(win\)/)
  assert.doesNotMatch(source, /devTools: process.env.NODE_ENV === 'development'/)
})

test('insights measure content height and retain all returned rows', () => {
  const source = read('src/renderer/overlay/ListenView.tsx')
  assert.match(source, /new ResizeObserver\(resize\)/)
  assert.match(source, /content.scrollHeight \+ topBarHeight/)
  assert.match(source, /ref=\{insightsContentRef\}/)
  assert.doesNotMatch(source, /\.slice\(0, 3\)/)
  assert.match(source, /Jetzt wichtig/)
  assert.doesNotMatch(source, /className="assistant-container" style=\{\{ width: '400px'/)
})

test('Ask measures streamed markdown before the final response settles', () => {
  const source = read('src/renderer/overlay/AskView.tsx')
  const liveSizing = source.slice(source.indexOf('// Measure rendered text'), source.indexOf('// Glass parity: Auto-scroll'))
  assert.match(liveSizing, /new ResizeObserver\(resizeStreamingContent\)/)
  assert.match(liveSizing, /observe\(markdown\)/)
  assert.match(liveSizing, /if \(!isStreaming \|\| !responseBufferRef.current.trim\(\)\) return/)
  assert.match(liveSizing, /requestWindowResize\(targetHeight\)/)
  assert.match(liveSizing, /resizeStreamingContent\(\);/)
  assert.match(liveSizing, /cancelAnimationFrame\(frame\)/)
})

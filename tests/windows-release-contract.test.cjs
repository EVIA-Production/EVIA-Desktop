const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..')
const read = (...parts) =>
  fs.readFileSync(path.join(root, ...parts), 'utf8').replace(/\r\n/g, '\n')

test('the Windows release builds one x64 and ARM64 NSIS installer', () => {
  const pkg = JSON.parse(read('package.json'))
  const command = pkg.scripts['build:release:win']
  assert.match(command, /build:native:audio:win/)
  assert.match(command, /build:native:glass/)
  assert.match(command, /electron-builder --win nsis --x64 --arm64 --publish never/)

  const builder = read('electron-builder.yml')
  assert.match(builder, /target: nsis\n\s+arch:\n\s+- x64\n\s+- arm64/)
  assert.match(builder, /buildUniversalInstaller: true/)
  assert.match(builder, /artifactName: "Taylos\.\$\{ext\}"/)
})

test('the packaged WASAPI fallback selects a native helper at runtime', () => {
  const service = read('src', 'main', 'system-audio-windows-service.ts')
  const build = read('scripts', 'build-windows-audio-helper.js')
  const builder = read('electron-builder.yml')

  assert.match(service, /process\.arch === 'arm64' \? 'arm64' : 'x64'/)
  assert.match(service, /'windows-audio', architecture, 'WASAPILoopback\.exe'/)
  assert.match(build, /name: 'x64'.*machine: 0x8664/)
  assert.match(build, /name: 'arm64'.*machine: 0xaa64/)
  assert.match(builder, /from: "native\/windows\/build"/)
})

test('the self-hosted workflow never queries the privileged runner-list endpoint', () => {
  const workflow = read('.github', 'workflows', 'release-windows-self-hosted.yml')
  const desktopWorkflow = read('.github', 'workflows', 'release-desktop.yml')
  assert.doesNotMatch(workflow, /actions\/runners/)
  assert.doesNotMatch(workflow, /push:\n\s+tags:/)
  assert.match(workflow, /workflow_call:/)
  assert.match(workflow, /runs-on: \[self-hosted, windows-signing\]/)
  assert.match(workflow, /default: false\n\s+type: boolean/)
  assert.match(desktopWorkflow, /uses: \.\/\.github\/workflows\/release-windows-self-hosted\.yml/)
  assert.match(desktopWorkflow, /windows-build-sign-and-publish:[\s\S]*upload: true/)
})


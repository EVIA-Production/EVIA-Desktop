test('the Windows signing runner is interactive, elevated, and proves the HSM before accepting jobs', () => {
  const starter = read('scripts', 'start-windows-signing-runner.ps1')
  const task = read('scripts', 'configure-windows-signing-runner-task.ps1')

  assert.match(starter, /Test-IsAdministrator/)
  assert.match(starter, /Get-Process -Name SimplySignDesktop/)
  assert.match(starter, /signtool sign \/fd SHA256/)
  assert.match(starter, /signtool verify \/pa \/v/)
  assert.match(starter, /Get-AuthenticodeSignature/)
  assert.match(task, /-LogonType Interactive -RunLevel Highest/)
  assert.match(task, /ProgramData.*Taylos\\signing-runner/)
  assert.match(task, /function Protect-ElevatedPath/)
  assert.match(task, /SetAccessRuleProtection\(\$true, \$false\)/)
  assert.match(task, /S-1-5-32-544/)
  assert.match(task, /Assert-ElevatedPathProtection \$RunnerRoot/)
  assert.match(task, /ExecutablePath\.StartsWith/)
  assert.match(task, /Runner processes remained after the scheduled task stopped/)
  assert.match(task, /does not execute the protected launcher/)
  assert.doesNotMatch(task, /-File `"\$starterSource`"/)
  assert.doesNotMatch(task, /New-Service|sc\.exe|LogonType Service/)
})


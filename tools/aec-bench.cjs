/**
 * The echo-cancellation gate.
 *
 *     node tools/aec-bench.cjs                 # gate the shipping canceller
 *     node tools/aec-bench.cjs --engine=speex  # the one it replaced
 *     node tools/aec-bench.cjs --engine=none   # sanity: the rig itself is honest
 *     node tools/aec-bench.cjs --wav           # also write audio to tools/aec-out/
 *
 * Nothing gets enabled in the app that has not passed this. Two rules earned
 * the hard way:
 *
 *   1. A canceller handed a SILENT reference has nothing to cancel and must
 *      return the microphone untouched. The Speex build failed this by 9dB and
 *      that single test, run on day one, would have saved a day of work.
 *   2. Results must DIFFER across echo delays. Identical numbers at 0, 60 and
 *      150ms mean the filter is not adapting to the reference at all - which is
 *      exactly what the Speex build showed at every filter length tried.
 *
 * The scenario is real speech (two voices, generated by `tools/make-speech.sh`)
 * through a synthetic but hardware-shaped room response, arranged in regions so
 * that echo and near end are never measured on the same material:
 *
 *     far only  |  near only  |  double talk
 *     0 ....11s      11..18s      18......29s
 *
 * Echo suppression is measured where only echo exists. Near-end damage is
 * measured where only the near end exists. Conflating them is how a canceller
 * that merely turns the rep down gets scored as if it were cancelling.
 */

const path = require('node:path');
const fs = require('node:fs');
const lab = require('./aec-lab.cjs');

process.setMaxListeners(0);

const RATE = 24_000;
const CHUNK = 2400;                    // 100ms, exactly what the pipeline hands over
const SPEECH_DIR = path.join(__dirname, 'aec-speech');
const OUT_DIR = path.join(__dirname, 'aec-out');

const args = process.argv.slice(2);
const argOf = (name, dflt) => {
  const hit = args.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : dflt;
};
const ENGINE = argOf('engine', 'aec3');
const WRITE_WAV = args.includes('--wav');

const fmt = (x, w = 5) => (x >= 0 ? '+' : '') + x.toFixed(1).padStart(w);
const pass = (ok) => (ok ? '\x1b[32mPASS\x1b[0m' : '\x1b[31mFAIL\x1b[0m');

// ─────────────────────────────────────────────────────────────────────────────
// Engines
// ─────────────────────────────────────────────────────────────────────────────

async function makeEngine(name) {
  if (name === 'none') {
    return {
      label: 'passthrough',
      process: (mic) => Float32Array.from(mic),
      dispose() {},
    };
  }

  if (name === 'speex') {
    const createAec = require('../src/renderer/aec/aec.js');
    const { requiredFilterSamples } = require('../dist/main/aec-reference.js');
    const M = await createAec();
    const FRAME = 160;
    const ptr = M._AecNew(FRAME, requiredFilterSamples(), RATE, 0);
    if (!ptr) throw new Error('AecNew failed');
    const cancel = M.cwrap('AecCancelEcho', null, ['number', 'number', 'number', 'number', 'number']);
    const micPtr = M._malloc(FRAME * 2);
    const refPtr = M._malloc(FRAME * 2);
    const outPtr = M._malloc(FRAME * 2);
    const put = (src, off, p) => {
      const h = new Int16Array(M.HEAP16.buffer, p, FRAME);
      for (let i = 0; i < FRAME; i += 1) {
        h[i] = Math.max(-32768, Math.min(32767, Math.round((src[off + i] || 0) * 32767)));
      }
    };
    return {
      label: `speex (${requiredFilterSamples()} taps)`,
      process(mic, ref) {
        const out = new Float32Array(mic.length);
        for (let off = 0; off + FRAME <= mic.length; off += FRAME) {
          put(mic, off, micPtr); put(ref, off, refPtr);
          cancel(ptr, micPtr, refPtr, outPtr, FRAME);
          const h = new Int16Array(M.HEAP16.buffer, outPtr, FRAME);
          for (let i = 0; i < FRAME; i += 1) out[off + i] = h[i] / 32768;
        }
        return out;
      },
      dispose() { M._AecDestroy(ptr); },
    };
  }

  if (name === 'aec3') {
    const { Aec3Canceller } = require('../dist/main/aec3-canceller.js');
    const canceller = await Aec3Canceller.create();
    return {
      label: `WebRTC AEC3 @${canceller.internalRate}Hz`,
      process: (mic, ref) => canceller.process(mic, ref),
      dispose: () => canceller.dispose(),
    };
  }

  throw new Error(`unknown engine: ${name}`);
}

/** Drive an engine over a whole stream in the pipeline's 100ms chunks. */
function runStream(engine, mic, ref) {
  const n = Math.floor(Math.min(mic.length, ref.length) / CHUNK) * CHUNK;
  const out = new Float32Array(n);
  for (let off = 0; off < n; off += CHUNK) {
    out.set(engine.process(mic.subarray(off, off + CHUNK), ref.subarray(off, off + CHUNK)), off);
  }
  return { out, n };
}

/** A fresh engine per scenario: adaptation state must never leak between tests. */
async function fresh(fn) {
  const engine = await makeEngine(ENGINE);
  try {
    return await fn(engine);
  } finally {
    engine.dispose();
  }
}

/**
 * The same audio through the same canceller with NOTHING to cancel.
 *
 * This is the honest baseline for "what did cancellation cost". It is not the
 * raw input: AEC3 resamples 24k -> 48k -> 24k and that round trip alone costs
 * about half a dB, which charged to the canceller would look like damage. The
 * port's own `pre` option would give the same thing for free and is unusable -
 * it runs a stateful resampler twice per frame and wrecks the real output by
 * 14dB. See the header of `src/main/aec3-canceller.ts`.
 */
async function idleOf(signal) {
  const silence = new Float32Array(signal.length);
  const { out } = await fresh((e) => runStream(e, signal, silence));
  return out;
}

